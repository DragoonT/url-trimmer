export function icon(name, className = "icon") {
  const body = PATHS[name];
  if (!body) return "";
  return `<svg class="${className}" ${SVG_ATTRS} aria-hidden="true">${body}</svg>`;
}

export function setIcon(el, name, className = "icon") {
  if (el) el.innerHTML = icon(name, className);
}

export function mountIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const extra = el.dataset.iconClass || "";
    setIcon(el, el.dataset.icon, extra ? `icon ${extra}` : "icon");
  });
}
